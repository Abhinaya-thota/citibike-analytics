"""Before/after optimization, measured with EXPLAIN ANALYZE.

The question: "hourly departures for one day" — the most common query shape
behind the dashboard and the forecast backtests.

DuckDB stores tables in row groups of ~122k rows and keeps a min/max "zone map"
per column per row group. A filter on started_at can skip every row group whose
[min, max] range can't match, but only if (a) the table is physically ordered so
each row group covers a narrow time range, and (b) the predicate is written
against the raw column so the optimizer can compare it to the zone map.

    A. table in load order    + sargable range predicate   (before)
    B. table sorted           + predicate wrapped in strftime()
    C. table sorted           + sargable range predicate   (after: what fct_trips does)

Writes analysis/06_explain_analyze_results.md. Run after `dbt build`.
"""

import os
import re
import statistics
import time
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
DB = os.environ.get("DUCKDB_PATH", ROOT / "data" / "warehouse" / "citibike.duckdb")
SCRATCH = ROOT / "data" / "warehouse" / "_bench.duckdb"
OUT = Path(__file__).with_name("06_explain_analyze_results.md")
DAY = "2026-07-15"

TABLES = {
    "A": "bench.main.trips_load_order",
    "B": "wh.marts.fct_trips",
    "C": "wh.marts.fct_trips",
}

QUERIES = {
    "A. load order, range predicate": f"""
        select hour(started_at) as hr, count(*) as departures
        from bench.trips_load_order
        where started_at >= timestamp '{DAY}' and started_at < timestamp '{DAY}' + interval 1 day
        group by hr order by hr""",
    "B. sorted, strftime() predicate": f"""
        select hour(started_at) as hr, count(*) as departures
        from wh.marts.fct_trips
        where strftime(started_at, '%Y-%m-%d') = '{DAY}'
        group by hr order by hr""",
    "C. sorted, range predicate": f"""
        select hour(started_at) as hr, count(*) as departures
        from wh.marts.fct_trips
        where started_at >= timestamp '{DAY}' and started_at < timestamp '{DAY}' + interval 1 day
        group by hr order by hr""",
}


def zone_map_overlap(con: duckdb.DuckDBPyConnection, table: str) -> tuple[int, int]:
    """(row groups whose started_at [min, max] overlaps DAY, total row groups),
    read straight from the zone-map statistics DuckDB keeps per row group."""
    db, schema, name = table.split(".")
    return con.execute(
        f"""
        with segs as (
            select row_group_id,
                   regexp_extract(stats, 'Min: ([^,]+),', 1)::timestamp as lo,
                   regexp_extract(stats, 'Max: ([^\\]]+)\\]', 1)::timestamp as hi
            from pragma_storage_info('{db}.{schema}.{name}')
            where column_name = 'started_at' and segment_type = 'TIMESTAMP'
        ),
        rgs as (select row_group_id, min(lo) as lo, max(hi) as hi from segs group by 1)
        select count(*) filter (where hi >= timestamp '{DAY}' and lo < timestamp '{DAY}' + interval 1 day),
               count(*)
        from rgs
        """
    ).fetchone()


def main() -> None:
    SCRATCH.unlink(missing_ok=True)
    con = duckdb.connect()
    con.execute(f"attach '{DB}' as wh (read_only)")
    con.execute(f"attach '{SCRATCH}' as bench")
    con.execute("set threads = 4")
    # Same rows as fct_trips, in the order the staging table holds them
    # (month batches, raw-file order within a month).
    con.execute("create table bench.trips_load_order as select * from wh.staging.stg_citibike__trips")

    total = con.execute("select count(*) from wh.marts.fct_trips").fetchone()[0]
    results = []
    for name, sql in QUERIES.items():
        con.execute(sql).fetchall()  # warm cache
        timings = []
        for _ in range(5):
            t = time.perf_counter()
            answer = con.execute(sql).fetchall()
            timings.append((time.perf_counter() - t) * 1000)
        plan = "\n".join(r[1] for r in con.execute("explain analyze " + sql).fetchall())
        hit, total_rgs = zone_map_overlap(con, TABLES[name[0]])
        # A function-wrapped predicate can't be compared with min/max stats.
        rg = f"{total_rgs} / {total_rgs}" if "strftime" in sql else f"{hit} / {total_rgs}"
        results.append((name, statistics.median(timings), plan, sum(r[1] for r in answer), rg))

    con.execute("detach bench")
    con.close()
    SCRATCH.unlink(missing_ok=True)

    lines = [
        "# EXPLAIN ANALYZE: zone-map pruning on fct_trips",
        "",
        f"Query: hourly departures on {DAY} over {total:,} trips. "
        "Median of 5 warm runs, 4 threads. Generated by `06_explain_analyze.py`.",
        "",
        "| variant | median ms | row groups that must be read | answer (trips) |",
        "|---|---:|---:|---:|",
    ]
    for name, ms, plan, answer, rg in results:
        lines.append(f"| {name} | {ms:.1f} | {rg} | {answer:,} |")
    a, b, c = results
    lines += [
        "",
        f"**Result.** The predicate matters most: wrapping `started_at` in `strftime()` "
        f"defeats zone maps and forces a full scan, {b[1] / c[1]:.0f}x slower than the "
        f"sargable range on the same table. Sorting then cuts the row groups read from "
        f"{a[4].split(' / ')[0]} to {c[4].split(' / ')[0]} ({a[1] / c[1]:.1f}x faster here). "
        "The gain from sorting is modest at this size because Citi Bike's raw files are "
        "already roughly time-ordered; it matters more on cold storage, where each skipped row group is a skipped read. "
        "Both are why `fct_trips` ends with `order by started_at` and the "
        "dashboard queries filter on raw timestamps.",
        "",
    ]
    lines += [
        "Row groups that must be read = row groups whose `started_at` min/max zone map overlaps",
        "the day (from `pragma_storage_info`). Everything else is skipped without being read.",
        "",
    ]
    for name, _, plan, _, _ in results:
        lines += [f"## {name}", "", "```", plan.strip(), "```", ""]
    OUT.write_text("\n".join(lines))
    print("\n".join(lines[:12]))


if __name__ == "__main__":
    main()
